// Embed Tailwind v4's stylesheet (theme, preflight, utilities) so the html block can compile Tailwind classes
// in the browser with no server and no network. Run after upgrading the tailwindcss package.
import { readFileSync, writeFileSync } from "node:fs";

const dir = "node_modules/tailwindcss/";
const files = ["index.css", "theme.css", "preflight.css", "utilities.css"];
const out = Object.fromEntries(files.map((f) => [f, readFileSync(dir + f, "utf8")]));
const version = JSON.parse(readFileSync(dir + "package.json", "utf8")).version;
writeFileSync(
  "src/html/tailwind-css.ts",
  `// Generated by scripts/gen-tailwind.mjs from tailwindcss@${version} (MIT). Do not edit.\nexport const TAILWIND_FILES: Record<string, string> = ${JSON.stringify(out)};\n`,
);
console.log(`wrote src/html/tailwind-css.ts (tailwindcss@${version})`);
